#Indexing means in the array where the elements are stored. The first element is stored at index 0, the second element is stored at index 1, and so on. The last element is stored at index -1, the second last element is stored at index -2, and so on.
import numpy as np
arr = np.array([10,20,30,40,50])
print(arr[0])
print(arr[-1])
print(arr[3])
print(arr[-4])